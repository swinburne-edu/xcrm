<script setup lang="ts">
import { router } from '@inertiajs/vue3';
import { computed, ref, watch } from 'vue';
import { selectClass } from '@/components/campaigns/types';
import EntityPicker from '@/components/crm/EntityPicker.vue';
import InputError from '@/components/InputError.vue';
import { Button } from '@/components/ui/button';
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Spinner } from '@/components/ui/spinner';
import type { ActivityDetail, ActivityOptions } from './types';

/**
 * Add or edit an activity with a high school. On create the cycle is the one chosen in the header; the check-in
 * link / QR code is generated by the server. The first staff member listed is the lead. "Đã diễn ra" is set by the
 * report on the detail page, not here.
 */
const props = defineProps<{ record: ActivityDetail | null; options: ActivityOptions }>();
const open = defineModel<boolean>('open', { default: false });

const isEdit = computed(() => props.record !== null);
const processing = ref(false);
const errors = ref<Record<string, string>>({});
const form = ref(blank());

function blank() {
    return {
        type: 'school_counseling',
        title: '',
        high_school_id: null as number | string | null,
        campaign_id: null as number | string | null,
        start_at: '',
        end_at: '',
        location: '',
        status: 'planned',
        expected_attendees: '' as number | string,
        staff_ids: [] as (number | string)[],
    };
}

watch(open, (isOpen) => {
    if (!isOpen) {
        return;
    }

    errors.value = {};
    const r = props.record;
    form.value = r
        ? {
              type: r.type,
              title: r.title,
              high_school_id: r.high_school_id,
              campaign_id: r.campaign_id,
              start_at: r.start_input ?? '',
              end_at: r.end_input ?? '',
              location: r.location ?? '',
              status: r.status === 'done' ? 'confirmed' : r.status,
              expected_attendees: r.expected_attendees ?? '',
              staff_ids: [...r.staff_ids],
          }
        : blank();
});

function fieldError(key: string): string | undefined {
    return Object.entries(errors.value).find(([k]) => k === key || k.startsWith(`${key}.`))?.[1];
}

function submit(): void {
    router.visit(isEdit.value ? `/school-activities/${props.record!.id}` : '/school-activities', {
        method: isEdit.value ? 'put' : 'post',
        // A new activity starts as "Dự kiến"; a finished one keeps its status (the report set it).
        data: { ...form.value, status: isEdit.value && props.record?.status !== 'done' ? form.value.status : undefined } as never,
        preserveScroll: true,
        preserveState: isEdit.value,
        onStart: () => (processing.value = true),
        onError: (e) => (errors.value = e),
        onSuccess: () => (open.value = false),
        onFinish: () => (processing.value = false),
    });
}
</script>

<template>
    <Dialog v-model:open="open">
        <DialogContent class="max-h-[90vh] overflow-y-auto sm:max-w-2xl" data-test="activity-form">
            <form class="grid gap-4" @submit.prevent="submit">
                <DialogHeader>
                    <DialogTitle>{{ isEdit ? 'Sửa hoạt động' : 'Thêm hoạt động tại trường' }}</DialogTitle>
                    <DialogDescription>Sau khi lưu, hệ thống tạo sẵn link và mã QR điểm danh để học sinh quét tại buổi tư vấn.</DialogDescription>
                </DialogHeader>

                <div class="grid gap-3 sm:grid-cols-[14rem_1fr]">
                    <div class="grid gap-1.5">
                        <Label for="a-type">Loại hoạt động <span class="text-destructive">*</span></Label>
                        <select id="a-type" v-model="form.type" :class="selectClass" data-test="activity-type">
                            <option v-for="t in options.types" :key="t.value" :value="t.value">{{ t.label }}</option>
                        </select>
                        <InputError :message="fieldError('type')" />
                    </div>
                    <div class="grid gap-1.5">
                        <Label for="a-title">Tên hoạt động <span class="text-destructive">*</span></Label>
                        <Input id="a-title" v-model="form.title" autocomplete="off" placeholder="VD: Tư vấn tuyển sinh tại THPT Chu Văn An" data-test="activity-title" />
                        <InputError :message="fieldError('title')" />
                    </div>
                </div>

                <div class="grid gap-3 sm:grid-cols-2">
                    <div class="grid gap-1.5">
                        <Label for="a-school">Trường THPT <span class="font-normal text-muted-foreground">(để trống nếu tổ chức tại campus)</span></Label>
                        <EntityPicker
                            id="a-school"
                            v-model="form.high_school_id"
                            entity="high_schools"
                            placeholder="Chọn trường"
                            :initial-items="record?.high_school_id ? [{ id: record.high_school_id, label: record.school ?? `#${record.high_school_id}`, description: null }] : []"
                        />
                        <InputError :message="fieldError('high_school_id')" />
                    </div>
                    <div class="grid gap-1.5">
                        <Label for="a-campaign">Chiến dịch</Label>
                        <EntityPicker
                            id="a-campaign"
                            v-model="form.campaign_id"
                            entity="campaigns"
                            placeholder="Không thuộc chiến dịch"
                            :initial-items="record?.campaign_id ? [{ id: record.campaign_id, label: record.campaign_name ?? `#${record.campaign_id}`, description: null }] : []"
                        />
                        <InputError :message="fieldError('campaign_id')" />
                    </div>
                </div>

                <div class="grid gap-3 sm:grid-cols-2">
                    <div class="grid gap-1.5">
                        <Label for="a-start">Bắt đầu</Label>
                        <Input id="a-start" v-model="form.start_at" type="datetime-local" data-test="activity-start" />
                        <InputError :message="fieldError('start_at')" />
                    </div>
                    <div class="grid gap-1.5">
                        <Label for="a-end">Kết thúc</Label>
                        <Input id="a-end" v-model="form.end_at" type="datetime-local" data-test="activity-end" />
                        <InputError :message="fieldError('end_at')" />
                    </div>
                </div>

                <div class="grid gap-3 sm:grid-cols-[1fr_10rem]">
                    <div class="grid gap-1.5">
                        <Label for="a-location">Địa điểm</Label>
                        <Input id="a-location" v-model="form.location" placeholder="Hội trường, sân trường…" />
                        <InputError :message="fieldError('location')" />
                    </div>
                    <div class="grid gap-1.5">
                        <Label for="a-expected">Dự kiến tham dự</Label>
                        <Input id="a-expected" v-model="form.expected_attendees" type="number" min="0" />
                        <InputError :message="fieldError('expected_attendees')" />
                    </div>
                </div>

                <div class="grid gap-1.5">
                    <Label for="a-staff">Nhân sự tham gia <span class="font-normal text-muted-foreground">(người đầu tiên là phụ trách)</span></Label>
                    <EntityPicker id="a-staff" v-model="form.staff_ids" entity="users" multiple placeholder="Chọn nhân sự" :initial-items="(record?.staff_items ?? []).map((s) => ({ id: s.id, label: s.label, description: null }))" />
                    <InputError :message="fieldError('staff_ids')" />
                </div>

                <div v-if="isEdit" class="grid gap-1.5 sm:max-w-xs">
                    <Label for="a-status">Trạng thái</Label>
                    <select id="a-status" v-model="form.status" :class="selectClass" :disabled="record?.status === 'done'" data-test="activity-status">
                        <option v-for="s in options.statuses.filter((x) => x.value !== 'done')" :key="s.value" :value="s.value">{{ s.label }}</option>
                    </select>
                    <InputError :message="fieldError('status')" />
                </div>

                <DialogFooter>
                    <Button type="button" variant="outline" @click="open = false">Huỷ</Button>
                    <Button type="submit" :disabled="processing" data-test="activity-submit">
                        <Spinner v-if="processing" />
                        {{ isEdit ? 'Lưu thay đổi' : 'Thêm hoạt động' }}
                    </Button>
                </DialogFooter>
            </form>
        </DialogContent>
    </Dialog>
</template>
